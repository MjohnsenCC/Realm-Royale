// Helper: get all realm enemy types for a difficulty zone and realm tier
export function getEnemyTypesForDifficultyZone(zone: number, realmTier: number = RealmTier.Wild): number[] {
  const tier = realmTier || RealmTier.Wild;
  return Object.values(REALM_ENEMY_DEFS)
    .filter((def) => def.difficultyZone === zone && (def.realmTier ?? RealmTier.Wild) === tier)
    .map((def) => def.type);
}

// Helper: get realm enemy types matching zone, biome affinity, and realm tier
export function getEnemyTypesForBiomeAndZone(
  biome: number,
  zone: number,
  realmTier: number = RealmTier.Wild
): number[] {
  const tier = realmTier || RealmTier.Wild;
  const matches = Object.values(REALM_ENEMY_DEFS).filter(
    (def) =>
      def.difficultyZone === zone &&
      (def.realmTier ?? RealmTier.Wild) === tier &&
      def.biomeAffinity &&
      def.biomeAffinity.includes(biome)
  );
  // If no biome-specific match, fall back to all enemies in that zone+tier
  if (matches.length === 0) return getEnemyTypesForDifficultyZone(zone, tier);
  return matches.map((def) => def.type);
}

