// --- Enemy Definition ---

export type EnemyShape =
  | "circle"
  | "diamond"
  | "triangle"
  | "square"
  | "hexagon"
  | "star";

export interface EnemyDefinition {
  type: number;
  biome: number;
  name: string;
  hp: number;
  speed: number;
  radius: number;
  aggroRange: number;
  leashRange: number;
  shootCooldown: number; // ms
  projectileDamage: number;
  projectileSpeed: number;
  projectileRange: number;
  shootingPattern: number;
  xpValue: number;
  shape: EnemyShape;
  color: number;
  projectileCollisionRadius?: number;
  difficultyZone?: number; // DifficultyZone value (realm overworld only)
  biomeAffinity?: number[]; // RealmBiome values this enemy prefers
  movementPattern?: number; // MovementPatternType value (realm overworld only)
  idleIntensity?: number; // IdleIntensity value (0=low, 1=medium, 2=high)
  dungeonDrop?: number; // DungeonType value — this enemy drops a portal for this dungeon
  dungeonDropChance?: number; // 0–1 probability of dropping the dungeon portal on kill (requires dungeonDrop)
  defaultDamageType?: number; // DamageType value (0=Physical, 1=Magic); defaults to Physical
  realmTier?: number; // RealmTier value (1=Wild, 2=Ruins, 3=DevineHell); undefined defaults to tier 1
}

